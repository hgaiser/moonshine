use async_shutdown::ShutdownManager;
use fec_rs::ReedSolomon;
use tokio::sync::mpsc;

use crate::crypto::encrypt_cbc;
use crate::session::SessionKeysReceiver;
use crate::session::manager::SessionShutdownReason;
use crate::session::stream::RtpHeader;
use crate::session::stream::StartWaiter;

use crate::session::stream::audio::OpusStreamConfig;
use crate::session::stream::audio::pulse_server::{AudioFrame, DEFAULT_CLOCK_RATE_HZ};

const NR_DATA_SHARDS: usize = 4;
const NR_PARITY_SHARDS: usize = 2;
const NR_TOTAL_SHARDS: usize = NR_DATA_SHARDS + NR_PARITY_SHARDS;
const MAX_SHARD_SIZE: usize = 2048_usize.div_ceil(16) * 16;

/// Moonlight's audio FEC reconstructs timestamps by adding the negotiated
/// packet duration (in milliseconds) for each successive RTP sequence number.
/// Using a 90 kHz clock here makes packets in the same FEC block disagree on
/// their base timestamp, preventing reliable recovery.
#[derive(Debug)]
struct AudioRtpClock {
	next_timestamp_ms: u32,
	packet_duration_ms: u32,
}

impl AudioRtpClock {
	fn new(packet_duration_ms: u32) -> Self {
		// Match PulseServer's fallback when an unsupported duration is received.
		let packet_duration_ms = match packet_duration_ms {
			5 | 10 => packet_duration_ms,
			_ => 1000 / DEFAULT_CLOCK_RATE_HZ,
		};
		Self {
			next_timestamp_ms: 0,
			packet_duration_ms,
		}
	}

	fn next_timestamp(&mut self) -> u32 {
		let timestamp = self.next_timestamp_ms;
		self.next_timestamp_ms = timestamp.wrapping_add(self.packet_duration_ms);
		timestamp
	}
}

#[derive(Debug)]
#[repr(C)]
struct AudioFecHeader {
	pub shard_index: u8,
	pub payload_type: u8,
	pub base_sequence_number: u16,
	pub base_timestamp: u32,
	pub ssrc: u32,
}

pub(crate) struct AudioEncoder {}

impl AudioEncoder {
	#[allow(clippy::too_many_arguments)]
	pub fn spawn(
		sample_rate: u32,
		packet_duration_ms: u32,
		stream_config: &OpusStreamConfig,
		frame_rx: crossbeam_channel::Receiver<AudioFrame>,
		frame_recycle_tx: crossbeam_channel::Sender<AudioFrame>,
		keys_rx: SessionKeysReceiver,
		encrypt: bool,
		packet_tx: mpsc::Sender<Vec<u8>>,
		stop: ShutdownManager<SessionShutdownReason>,
		start: StartWaiter,
	) -> Result<(), ()> {
		tracing::debug!("Starting audio encoder.");
		tracing::debug!(
			"Creating audio encoder with sample rate {}, {} channels ({} streams, {} coupled).",
			sample_rate,
			stream_config.channels,
			stream_config.streams,
			stream_config.coupled_streams,
		);

		let mut encoder = opus::MSEncoder::new(
			sample_rate,
			stream_config.streams,
			stream_config.coupled_streams,
			&stream_config.mapping[..stream_config.channels as usize],
			opus::Application::LowDelay,
		)
		.map_err(|e| tracing::warn!("Failed to create audio encoder: {e}"))?;

		// Moonlight expects a constant bitrate.
		encoder
			.set_vbr(false)
			.map_err(|e| tracing::warn!("Failed to disable variable bitrate: {e}"))?;
		encoder
			.set_bitrate(opus::Bitrate::Bits(stream_config.bitrate as i32))
			.map_err(|e| tracing::warn!("Failed to set audio bitrate: {e}"))?;

		let fec_encoder = ReedSolomon::new(NR_DATA_SHARDS, NR_PARITY_SHARDS)
			.map_err(|e| tracing::warn!("Failed to create FEC encoder: {e}"))?;

		let inner = AudioEncoderInner {};
		std::thread::Builder::new()
			.name("audio-encode".to_string())
			.spawn(move || {
				inner.run(
					frame_rx,
					frame_recycle_tx,
					packet_duration_ms,
					fec_encoder,
					encoder,
					keys_rx,
					encrypt,
					packet_tx,
					stop,
					start,
				)
			})
			.map_err(|e| tracing::error!("Failed to start audio encode thread: {e}"))?;

		Ok(())
	}
}

struct AudioEncoderInner {}

impl AudioEncoderInner {
	#[allow(clippy::too_many_arguments)]
	fn run(
		self,
		frame_rx: crossbeam_channel::Receiver<AudioFrame>,
		frame_recycle_tx: crossbeam_channel::Sender<AudioFrame>,
		packet_duration_ms: u32,
		mut fec_encoder: ReedSolomon,
		mut encoder: opus::MSEncoder,
		keys_rx: SessionKeysReceiver,
		encrypt: bool,
		packet_tx: mpsc::Sender<Vec<u8>>,
		stop: ShutdownManager<SessionShutdownReason>,
		mut start: StartWaiter,
	) {
		// Trigger session shutdown when the audio encoder stops.
		let _session_stop_token = stop.trigger_shutdown_token(SessionShutdownReason::AudioEncoderStopped);
		let _delay_stop = stop.delay_shutdown_token();

		// Wait for the start signal before entering the encode loop.
		let rt = tokio::runtime::Builder::new_current_thread()
			.enable_all()
			.build()
			.expect("Failed to build tokio runtime for audio encoder");
		if !rt.block_on(start.wait(&stop)) {
			tracing::debug!("Audio encoder stopped before start signal.");
			return;
		}

		let mut sequence_number = 0u16;
		let mut rtp_clock = AudioRtpClock::new(packet_duration_ms);

		// For unknown reasons, the RS parity matrix computed by our RS implementation.
		// doesn't match the one Nvidia uses for audio data. I'm not exactly sure why,
		// but we can simply replace it with the matrix generated by OpenFEC which
		// works correctly. This is possible because the data and FEC shard count is
		// constant and known in advance.
		// Source: https://github.com/moonlight-stream/moonlight-common-c/blob/5de4a5b85a28d8d639482a1a105c3a06eb67a2fd/src/RtpAudioQueue.c#L57.
		// TODO: Find a way to fix this, it is very ugly..
		fec_encoder
			.set_parity_matrix(&[0x77, 0x40, 0x38, 0x0e, 0xc7, 0xa7, 0x0d, 0x6c])
			.expect("Moonlight audio parity matrix must match Reed-Solomon shard layout");
		let mut fec_encoder = fec_rs::ShardByShard::new(&fec_encoder);

		let mut shards = vec![vec![0u8; MAX_SHARD_SIZE]; NR_TOTAL_SHARDS];

		// These values will be used for the parity shards, but they need to be copied from the first data shard.
		let mut base_sequence_number = 0u16;
		let mut base_timestamp = 0u32;

		// A buffer for an audio sample after it has been encoded.
		// TODO: Decide the correct size for this buffer.
		let mut encoded_audio = vec![0u8; 1400];

		// Pre-seed the recycling pipeline with empty frames.
		for _ in 0..3 {
			let _ = frame_recycle_tx.send(AudioFrame {
				buf: Vec::new(),
				capture_ts_ms: 0,
			});
		}

		while !stop.is_shutdown_triggered() {
			let frame = match frame_rx.recv() {
				Ok(frame) => frame,
				Err(_) => {
					tracing::debug!("PulseServer channel closed.");
					break;
				},
			};

			// Timestamp advances only after a packet has been successfully encoded.
			let encoded_size = match encoder.encode_float(&frame.buf, &mut encoded_audio) {
				Ok(encoded_size) => encoded_size,
				Err(e) => {
					tracing::warn!("Failed to encode audio: {e}");
					let _ = encoder
						.reset_state()
						.map_err(|e| tracing::warn!("Failed to reset Opus encoder state: {e}"));
					// Return the frame for recycling even on error.
					let _ = frame_recycle_tx.try_send(AudioFrame {
						buf: frame.buf,
						capture_ts_ms: 0,
					});
					continue;
				},
			};

			// Read current keys from watch channel.
			let keys = &*keys_rx.borrow();

			// Encrypt the audio data if encryption is enabled.
			let payload = match encrypt {
				true => {
					let iv = keys.remote_input_key_id as u32 + sequence_number as u32;
					let mut iv = iv.to_be_bytes().to_vec();
					iv.extend([0u8; 12]);
					match encrypt_cbc(&encoded_audio[..encoded_size], &keys.remote_input_key, &iv) {
						Ok(payload) => payload,
						Err(e) => {
							tracing::warn!("Failed to encrypt audio: {e}");
							let _ = frame_recycle_tx.try_send(AudioFrame {
								buf: frame.buf,
								capture_ts_ms: 0,
							});
							continue;
						},
					}
				},
				false => encoded_audio[..encoded_size].to_vec(),
			};

			// Advance only when an audio packet is ready to transmit; errors must
			// not create a gap in the FEC block's inferred base timestamp.
			let timestamp = rtp_clock.next_timestamp();

			let shard = &mut shards[sequence_number as usize % NR_DATA_SHARDS];

			{
				// Set the RTP header in the memory of the shard.
				let rtp_header = unsafe { &mut *(shard.as_mut_ptr() as *mut RtpHeader) };
				rtp_header.header = 0x80u8.to_be();
				rtp_header.packet_type = 97u8.to_be();
				rtp_header.sequence_number = sequence_number.to_be();
				rtp_header.timestamp = timestamp.to_be();
				rtp_header.ssrc = 0;

				// For FEC, copy the sequence number and timestamp of the first of the sequence of audio packets.
				if (sequence_number as usize).is_multiple_of(NR_DATA_SHARDS) {
					// Copy some values, but note that they are big-endian (as expected by Moonlight).
					base_sequence_number = rtp_header.sequence_number;
					base_timestamp = rtp_header.timestamp;
				}
			}

			sequence_number = sequence_number.wrapping_add(1);

			// Copy the payload to the shard.
			unsafe {
				std::ptr::copy_nonoverlapping(
					payload.as_ptr(),
					shard.as_mut_ptr().add(std::mem::size_of::<RtpHeader>()),
					payload.len(),
				);
			}

			// Crop the shard to the length that we want to send it.
			let data_shard_size = std::mem::size_of::<RtpHeader>() + payload.len();
			let data_shard = shard[..data_shard_size].to_vec();

			if packet_tx.blocking_send(data_shard).is_err() {
				tracing::debug!("Failed to send packet over channel, channel is likely closed.");
				break;
			}

			{
				// Create a view of just the data itself for encoding.
				let mut shards: Vec<&mut [u8]> = shards.iter_mut().map(|s| &mut s[..data_shard_size]).collect();
				if let Err(e) = fec_encoder.encode(&mut shards) {
					tracing::warn!("Failed to encode data shard in FEC block: {e}");
				}
			}

			// If the last packet, compute and send parity shards.
			if (sequence_number as usize).is_multiple_of(NR_DATA_SHARDS) {
				if fec_encoder.reset().is_err() {
					tracing::warn!("Parity is not ready, but we were expecting it to be ready.");
					fec_encoder.reset_force();
					let _ = frame_recycle_tx.try_send(AudioFrame {
						buf: frame.buf,
						capture_ts_ms: 0,
					});
					continue;
				}

				for (shard_index, shard) in shards[NR_DATA_SHARDS..].iter_mut().enumerate() {
					{
						let rtp_header = unsafe { &mut *(shard.as_mut_ptr() as *mut RtpHeader) };
						rtp_header.sequence_number = (sequence_number + shard_index as u16).to_be();
						rtp_header.packet_type = 127u8.to_be();
						rtp_header.timestamp = 0u32.to_be();
						rtp_header.ssrc = 0u32.to_be();
					}

					// Make room for the AudioFecHeader by moving the payload back.
					unsafe {
						std::ptr::copy(
							shard.as_mut_ptr().add(std::mem::size_of::<RtpHeader>()),
							shard
								.as_mut_ptr()
								.add(std::mem::size_of::<RtpHeader>() + std::mem::size_of::<AudioFecHeader>()),
							payload.len(),
						);
					}

					{
						let fec_header = unsafe {
							&mut *(shard.as_mut_ptr().add(std::mem::size_of::<RtpHeader>()) as *mut AudioFecHeader)
						};
						fec_header.shard_index = (shard_index as u8).to_be();
						fec_header.payload_type = 97u8.to_be();
						fec_header.base_sequence_number = base_sequence_number;
						fec_header.base_timestamp = base_timestamp;
						fec_header.ssrc = 0u32;
					}

					let parity_shard_size =
						std::mem::size_of::<RtpHeader>() + std::mem::size_of::<AudioFecHeader>() + payload.len();
					let parity_shard = shard[..parity_shard_size].to_vec();

					if packet_tx.blocking_send(parity_shard).is_err() {
						tracing::debug!("Failed to send packet over channel, channel is likely closed.");
						break;
					}
				}
			}

			// Return the empty frame for recycling.
			let _ = frame_recycle_tx.try_send(AudioFrame {
				buf: frame.buf,
				capture_ts_ms: 0,
			});
		}

		tracing::debug!("Audio encoder stopped.");
	}
}

#[cfg(test)]
mod tests {
	use super::AudioRtpClock;

	#[test]
	fn timestamps_match_moonlight_audio_fec_block_layout() {
		for duration_ms in [5, 10] {
			let mut clock = AudioRtpClock::new(duration_ms);
			for block in 0..3u32 {
				let timestamps = [
					clock.next_timestamp(),
					clock.next_timestamp(),
					clock.next_timestamp(),
					clock.next_timestamp(),
				];
				let base = block * 4 * duration_ms;
				for (index, timestamp) in timestamps.into_iter().enumerate() {
					assert_eq!(timestamp, base + index as u32 * duration_ms);
					// The receiver infers a common FEC base timestamp from any
					// packet's timestamp and its index inside the four-shard block.
					assert_eq!(timestamp - index as u32 * duration_ms, base);
				}
			}
		}
	}

	#[test]
	fn timestamps_wrap_without_overflow() {
		let mut clock = AudioRtpClock {
			next_timestamp_ms: u32::MAX - 4,
			packet_duration_ms: 5,
		};
		assert_eq!(clock.next_timestamp(), u32::MAX - 4);
		assert_eq!(clock.next_timestamp(), 0);
		assert_eq!(clock.next_timestamp(), 5);
	}

	#[test]
	fn unsupported_packet_duration_matches_pulse_server_fallback() {
		let mut clock = AudioRtpClock::new(0);
		assert_eq!(clock.next_timestamp(), 0);
		assert_eq!(clock.next_timestamp(), 5);
	}
}
